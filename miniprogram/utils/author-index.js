/** 作者一格其实是书名的那几部结集 */
const COLLECTIVE = { 礼记: 1, 论语: 1, 国语: 1, 战国策: 1 };

/** 归一到通行名。查不到就原样返回（去掉首尾空白） */
function aliasOf(name) {
  const n = String(name == null ? "" : name).trim();
  if (!n) return "";
  return ALIAS[n] || n;
}

/** 这条「作者」是不是一部结集（《礼记》《论语》《国语》《战国策》） */
function isCollective(name) {
  return !!COLLECTIVE[aliasOf(name)];
}

