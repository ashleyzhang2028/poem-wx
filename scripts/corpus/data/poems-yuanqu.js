(function () {
  window.YUANQU_ALL = window.POEMS_YUANQU;
  window.getYuanquById = function (id) {
    return window.POEMS_YUANQU.filter(function (p) { return p.id === id; })[0] || null;
  };
  window.getYuanquGroups = function () {
    var groups = [];
    window.POEMS_YUANQU.forEach(function (p) {
      var g = p.gradeGroup || "其他";
      var hit = groups.filter(function (it) { return it.name === g; })[0];
      if (!hit) { hit = { name: g, items: [] }; groups.push(hit); }
      hit.items.push(p);
    });
    return groups;
  };
})();
